const messages: Record<Locale, Record<keyof typeof zh, string>> = { zh, en }

export type I18nKey = keyof typeof zh

function browserLocale(): Locale {
  if (typeof navigator !== 'undefined' && navigator.language.toLowerCase().startsWith('zh')) {
    return 'zh'
  }
  return 'en'
}

function storedLocale(): Locale | null {
  if (typeof window === 'undefined') return null
  const value = window.localStorage.getItem(STORAGE_KEY)
  return value === 'zh' || value === 'en' ? value : null
}

export const currentLocale = ref<Locale>(storedLocale() ?? browserLocale())

export const languageOptions = computed(() => [
  { value: 'zh' as const, label: messages[currentLocale.value]['language.zh'] },
  { value: 'en' as const, label: messages[currentLocale.value]['language.en'] },
])

export const currentLanguageLabel = computed(() => messages[currentLocale.value][`language.${currentLocale.value}`])

export function setLocale(locale: Locale) {
  currentLocale.value = locale
  if (typeof document !== 'undefined') {
    document.documentElement.lang = locale === 'zh' ? 'zh-CN' : 'en'
  }
  if (typeof window !== 'undefined') {
    window.localStorage.setItem(STORAGE_KEY, locale)
  }
}

// tIn renders a key in an explicitly named language. It exists for the callers
// that must not read the ambient locale -- a test asserting both languages, or
// a renderer told which language to speak -- so a locale and a translation can
// never disagree about which language they are in.
export function tIn(locale: Locale, key: I18nKey, params?: Record<string, string | number>): string {
  let text = messages[locale][key] ?? zh[key] ?? key
  if (params) {
    for (const [name, value] of Object.entries(params)) {
      text = text.split(`{${name}}`).join(String(value))
    }
  }
  return text
}

export function t(key: I18nKey, params?: Record<string, string | number>): string {
  return tIn(currentLocale.value, key, params)
}

