-- terms is the only searched column: it holds the line's text after Chinese
-- word segmentation, and to_tsvector('simple', …) splits it on the spaces the
-- segmenter left without stemming or a dictionary, exactly as FTS5's tokenizer
-- does. The rest is addressing, so a match can be tied back to the file and
-- line it came from. terms_tsv and its index are this engine's half of that
-- (design §2.5).
CREATE TABLE fb_memory_fts (
  -- SQLite's rowid, which fb_memory_index_files.first_rowid addresses.
  row_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
  terms TEXT NOT NULL,
  root TEXT NOT NULL,
  path TEXT NOT NULL,
  line_no BIGINT NOT NULL,
  terms_tsv tsvector GENERATED ALWAYS AS (to_tsvector('simple', terms)) STORED
);
CREATE INDEX fb_memory_fts_terms_gin ON fb_memory_fts USING gin (terms_tsv);

