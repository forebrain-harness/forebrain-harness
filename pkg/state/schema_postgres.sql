  CHECK (TRIM(agent_id) <> ''),
  CHECK (input_set IN (0, 1)),
  CHECK (origin IN ('api', 'web', 'cron', 'channel'))
);
CREATE INDEX idx_fb_tasks_project_updated ON fb_tasks (project_id, updated_at DESC);
CREATE INDEX idx_fb_tasks_external_ref ON fb_tasks (project_id, external_ref)
  WHERE external_ref <> '';

-- One execution of a task: exactly one conversation and one task workspace.
CREATE TABLE fb_task_executions (
  session_id TEXT NOT NULL PRIMARY KEY REFERENCES fb_sessions (id) ON DELETE CASCADE,
  task_id TEXT NOT NULL REFERENCES fb_tasks (id) ON DELETE CASCADE,
  seq BIGINT NOT NULL,
  workspace TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'pending',
  error_code TEXT NOT NULL DEFAULT '',
  error_text TEXT NOT NULL DEFAULT '',
  -- Why the end-of-execution notification could not be delivered.
  notify_error TEXT NOT NULL DEFAULT '',
  started_at BIGINT,
  finished_at BIGINT,
  created_at BIGINT NOT NULL,
  UNIQUE (task_id, seq),
  CHECK (seq > 0),
  CHECK (status IN ('pending', 'running', 'stopped', 'completed', 'failed'))
);

-- The install's runtime configuration, one row per root section of
-- forebrain.yaml (plan 187).
CREATE TABLE fb_config (
  section TEXT NOT NULL PRIMARY KEY,
  value_json TEXT NOT NULL,
  updated_at_ms BIGINT NOT NULL
);

-- MCP OAuth refresh tokens, one row per (namespace, server). An empty
-- project_key is the shared global store.
CREATE TABLE fb_mcp_oauth (
  project_key TEXT NOT NULL,
  server_name TEXT NOT NULL,
  value_json TEXT NOT NULL,
  updated_at_ms BIGINT NOT NULL,
  PRIMARY KEY (project_key, server_name)
);

-- The read baseline a conversation keeps across processes (plan 183): for a
-- path read_file put in front of the model, the version it showed.
CREATE TABLE fb_file_read_states (
  session_id TEXT NOT NULL REFERENCES fb_sessions (id) ON DELETE CASCADE,
  agent_id TEXT NOT NULL,
  path TEXT NOT NULL,
  mod_time_ns BIGINT NOT NULL,
  size BIGINT NOT NULL,
  sha256 TEXT NOT NULL,
  read_at_ns BIGINT NOT NULL,
  touch_kind TEXT NOT NULL DEFAULT 'read',
  PRIMARY KEY (session_id, path),
  CHECK (TRIM(agent_id) <> ''),
  CHECK (touch_kind = 'read')
);
