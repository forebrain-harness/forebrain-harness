-- The state schema in PostgreSQL 14: the same tables, columns and index names
-- as schema.sql, in PostgreSQL's types and DDL (plan 209, design §2.4, §2.9).
--
-- schema.sql is the SQLite file and is never edited. This file declares the
-- same version of the same shape; a fresh PostgreSQL database is created from
-- it whole and stamped with the version in fb_schema_version, and later
-- migrations carry both files forward together.
--
-- How the translation goes:
--   INTEGER                     -> BIGINT (every stored time is milliseconds)
--   TEXT                        -> TEXT (PostgreSQL has no reason to narrow it)
--   AUTOINCREMENT               -> GENERATED BY DEFAULT AS IDENTITY
--   STRICT / WITHOUT ROWID      -> dropped (PostgreSQL has neither)
--   a partial index             -> kept, WHERE clause and all
--   a table whose rows the store orders by SQLite's rowid gets an explicit
--   row_id identity column, which the PostgreSQL statements order by
--   the full-text index             -> a generated tsvector column plus GIN
--                                      (design §2.5)
--
-- The store writes every string as TEXT, and PostgreSQL lets a table hold
-- exactly that, so the only names an idx_ prefix is not shared with schema.sql
-- on are the ones this engine has to add: the tsvector column and its index.
-- Every statement ends with ';' and the executor runs them one at a time.

CREATE TABLE fb_schema_version (
  version BIGINT NOT NULL
);

