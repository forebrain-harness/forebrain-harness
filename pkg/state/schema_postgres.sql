-- The compact/context-reset pointers reference fb_messages rows, and
-- fb_messages references this table back; PostgreSQL, like SQLite, checks
-- foreign keys at DML time, so the cycle is declarable — the two constraints
-- are added after fb_messages exists, below.
CREATE TABLE fb_sessions (
  id TEXT NOT NULL PRIMARY KEY,
  agent_id TEXT NOT NULL,
  title TEXT NOT NULL,
  parent_session_id TEXT REFERENCES fb_sessions (id) ON DELETE SET NULL,
  project_id TEXT REFERENCES fb_projects (id) ON DELETE SET NULL,
  origin TEXT NOT NULL DEFAULT 'native',
  -- source marks what a session is FOR ('' = an ordinary conversation,
  -- 'workshop' = a skill-workshop task).
  source TEXT NOT NULL DEFAULT '',
  -- The project type this conversation was born with, frozen at birth.
  project_type TEXT NOT NULL DEFAULT 'coding',
  cwd TEXT NOT NULL DEFAULT '',
  git_branch TEXT NOT NULL DEFAULT '',
  memory_mode TEXT NOT NULL DEFAULT 'disabled',
  memory_source TEXT NOT NULL DEFAULT '',
  initial_window_id TEXT NOT NULL DEFAULT '',
  compact_boundary_message_id BIGINT,
  context_reset_message_id BIGINT,
  created_at BIGINT NOT NULL,
  updated_at BIGINT NOT NULL,
  UNIQUE (id, agent_id),
  CHECK (TRIM(agent_id) <> ''),
  CHECK (TRIM(title) <> ''),
  CHECK (origin IN ('native', 'migrated')),
  CHECK (project_type IN ('office', 'coding', 'batch')),
  CHECK (created_at > 0),
  CHECK (updated_at > 0)
);
CREATE INDEX idx_fb_sessions_agent_updated ON fb_sessions (agent_id, updated_at DESC);
CREATE INDEX idx_fb_sessions_agent_project ON fb_sessions (agent_id, project_id, updated_at DESC);
CREATE INDEX idx_fb_sessions_parent ON fb_sessions (parent_session_id)
  WHERE parent_session_id IS NOT NULL;

CREATE TABLE fb_runs (
  id TEXT NOT NULL PRIMARY KEY,
  -- SQLite's rowid: the order runs were inserted in, which the store falls
  -- back on when two timestamps tie.
  row_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
  session_id TEXT NOT NULL REFERENCES fb_sessions (id) ON DELETE CASCADE,
  parent_run_id TEXT REFERENCES fb_runs (id) ON DELETE CASCADE,
  input_text TEXT NOT NULL,
  status TEXT NOT NULL,
  usage_prompt_tokens BIGINT NOT NULL DEFAULT 0,
  usage_completion_tokens BIGINT NOT NULL DEFAULT 0,
  usage_cache_read_tokens BIGINT NOT NULL DEFAULT 0,
  usage_cache_creation_tokens BIGINT NOT NULL DEFAULT 0,
  usage_llm_calls BIGINT NOT NULL DEFAULT 0,
  -- Wall-clock time spent waiting on model requests during this run.
  usage_llm_ms BIGINT NOT NULL DEFAULT 0,
  started_at_ms BIGINT,
  finished_at_ms BIGINT,
  worked_ms BIGINT,
  created_at BIGINT NOT NULL,
  updated_at BIGINT NOT NULL,
  -- owner is the process driving the run, meaningful only while it is running.
  owner TEXT NOT NULL DEFAULT '',
  -- How long the turn waited for the model's first output.
  first_token_ms BIGINT,
  CHECK (status IN ('running', 'waiting_action', 'done', 'failed', 'cancelled')),
  CHECK ((started_at_ms IS NULL) = (finished_at_ms IS NULL)
     AND (finished_at_ms IS NULL) = (worked_ms IS NULL))
);
CREATE INDEX idx_fb_runs_session ON fb_runs (session_id, updated_at DESC);
CREATE INDEX idx_fb_runs_parent ON fb_runs (parent_run_id) WHERE parent_run_id IS NOT NULL;
CREATE INDEX idx_fb_runs_active ON fb_runs (status, updated_at DESC)
  WHERE status IN ('running', 'waiting_action');
-- The session-exclusivity check CreateRun runs before inserting a primary run:
