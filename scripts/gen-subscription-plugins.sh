#!/usr/bin/env bash
# Generate the local subscription-plugin bridges for the Go binary and the web
# UI. Subscription plugins (qodercn, workbuddy, …) are in-tree source under
# plugins/subscriptions/<id>/; this script only turns their presence into the
# two import bridges the Go and TypeScript builds need.
#
# Plugin layout it discovers (either file is optional, directory order is the
# plugin id):
#
#   plugins/subscriptions/<id>/plugin.go          Go plugin; package registers
#                                                 itself in init() (provider,
#                                                 LLM factory, subscription)
#   plugins/subscriptions/<id>/frontend/index.ts  frontend plugin definition
#                                                 (default export)
#
# Bridges it generates (both committed, both refreshed in place):
#
#   cmd/forebrain/plugins_local_gen.go             blank-imports every Go plugin
#                                                  so its init() runs in the
#                                                  binary; deleted when the last
#                                                  plugin is gone
#   frontend/src/plugins/local_subscriptions.gen.ts  always present; empty when
#                                                  no plugin ships a frontend
#                                                  definition, so the tree
#                                                  typechecks without any plugin
#                                                  on disk
#
# Idempotent and safe to run concurrently (make ui / make build / the release
# script all call it): each bridge is written to a temp file beside its target
# and moved into place, so a reader never sees a half-written file.

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
ROOT_DIR="$(cd "$SCRIPT_DIR/.." && pwd)"

PLUGINS_DIR="$ROOT_DIR/plugins/subscriptions"
GO_BRIDGE="$ROOT_DIR/cmd/forebrain/plugins_local_gen.go"
TS_BRIDGE="$ROOT_DIR/frontend/src/plugins/local_subscriptions.gen.ts"
MODULE="github.com/forebrain-harness/forebrain-harness"

go_ids=()
ts_ids=()
if [ -d "$PLUGINS_DIR" ]; then
  for dir in "$PLUGINS_DIR"/*/; do
    [ -d "$dir" ] || continue
    id="$(basename "$dir")"
    if [ -f "$dir/plugin.go" ]; then
      go_ids+=("$id")
    fi
    if [ -f "$dir/frontend/index.ts" ]; then
      ts_ids+=("$id")
    fi
  done
fi

# --- Go bridge ---------------------------------------------------------------
# The blank imports run every plugin's init(); with no plugin on disk the file
# is removed so `go build ./cmd/forebrain` works on a pristine checkout.

if [ "${#go_ids[@]}" -eq 0 ]; then
  rm -f "$GO_BRIDGE"
else
  {
    echo "// Code generated by scripts/gen-subscription-plugins.sh; DO NOT EDIT."
    echo
    echo "package main"
    echo
    echo "import ("
    for id in "${go_ids[@]}"; do
      echo "	_ \"$MODULE/plugins/subscriptions/$id\""
    done
    echo ")"
  } > "$GO_BRIDGE.tmp"
  mv "$GO_BRIDGE.tmp" "$GO_BRIDGE"
fi

# --- Frontend bridge ---------------------------------------------------------
# frontend/src/plugins/local_subscriptions.gen.ts sits three directories below
# the repository root, so a plugin's index.ts is reached at
# ../../../plugins/subscriptions/<id>/frontend/index.

mkdir -p "$(dirname "$TS_BRIDGE")"
{
  echo "// Code generated by scripts/gen-subscription-plugins.sh; DO NOT EDIT."
  echo "import type { SubscriptionFrontendPlugin } from './subscriptionPlugin'"
  echo
  if [ "${#ts_ids[@]}" -eq 0 ]; then
    echo "export const localSubscriptionPlugins: SubscriptionFrontendPlugin[] = []"
  else
    idx=0
    for id in "${ts_ids[@]}"; do
      echo "import plugin_${idx} from '../../../plugins/subscriptions/$id/frontend/index'"
      idx=$((idx + 1))
    done
    echo
    echo "export const localSubscriptionPlugins: SubscriptionFrontendPlugin[] = ["
    idx=0
    for id in "${ts_ids[@]}"; do
      echo "  plugin_${idx},"
      idx=$((idx + 1))
    done
    echo "]"
  fi
} > "$TS_BRIDGE.tmp"
mv "$TS_BRIDGE.tmp" "$TS_BRIDGE"

echo "gen-subscription-plugins: ${#go_ids[@]} Go plugin(s), ${#ts_ids[@]} frontend plugin(s) bridged"
